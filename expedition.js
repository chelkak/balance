// ── Случайность, привязанная к seed ───────────────────────────────────
// Экспедиция обязана быть одинаковой при каждом открытии: перезагрузил
// приложение — путь, встречи и добыча те же. Поэтому ни одного
// Math.random() внутри разрешения экспедиции.
function expRand(seed, шаг){
  let h = (seed ^ (шаг * 0x9e3779b9)) >>> 0;
  h = (h ^ (h >>> 16)) >>> 0;
  h = Math.imul(h, 0x85ebca6b) >>> 0;
  h = (h ^ (h >>> 13)) >>> 0;
  h = Math.imul(h, 0xc2b2ae35) >>> 0;
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

// ── Профиль находки ───────────────────────────────────────────────────
// Строится по тому, что доступно во время работы: номер находки, её
// редкость и земля происхождения. Ни одного обращения к названию —
// deck.js остаётся запечатанным.
//
// Детерминированность обязательна: одна и та же находка всегда даёт
// один и тот же профиль, иначе полка меняла бы смысл между заходами.
function gearProfile(i){
  const f = (typeof FINDS !== "undefined") ? FINDS[i] : null;
  if(!f) return null;
  const земля = landOf(i);
  const спец = LAND_SPEC[земля] || LAND_SPEC[0];
  const p = {
    i, r:f.r, земля,
    stat: спец.s,
    сила: 1,
    тема: спец.тема,
    эффект: null,
    правило: null
  };
  if(f.r === 1){                       // редкая: единица плюс один эффект
    p.эффект = спец.э;
  }
  if(f.r === 2){                       // легендарная: единица плюс правило
    p.правило = LEGEND_RULE[земля] || LEGEND_RULE[0];
  }
  return p;
}

