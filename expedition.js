// Чего просит маршрут по каждой характеристике.
function routeNeeds(маршрут){
  const н = {чутьё:0, ловкость:0, смелость:0};
  (маршрут.узлы || []).forEach(у => {
    if(у.скрыт) return;
    const n = NODE_BY_ID[у.id];
    if(n) н[n.s] = Math.max(н[n.s], у.нужно);
  });
  return н;
}

// Слабое место словами. Не «провал», а «вот это пока не закрыто».
function weakSpot(маршрут, сборка){
  const дыры = [];
  (маршрут.узлы || []).forEach(у => {
    if(у.скрыт) return;
    const n = NODE_BY_ID[у.id];
    if(n && сборка.s[n.s] < у.нужно) дыры.push(n.t.toLowerCase());
  });
  const скрытых = (маршрут.узлы || []).filter(у => у.скрыт).length;
  if(!дыры.length)
    return скрытых ? "Известные встречи закрыты. Один узел останется неизвестным."
                   : "Известные встречи закрыты.";
  return `Пока не закрыто: ${дыры.join(", ")}.`;
}

// Один и тот же seed для одной земли и маршрута в течение дня: иначе
// экран подготовки показывал бы разные встречи при каждой перерисовке.
function expSeedFor(земля, тип){
  const d = todayKey().replace(/-/g, "");
  let h = ((PET.deckSeed || 1) ^ 0x5bf03635) >>> 0;
  const строка = d + "|" + земля + "|" + тип;
  for(let i = 0; i < строка.length; i++){
    h = (h ^ строка.charCodeAt(i)) >>> 0;
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

// Факт утренней записи — единственная связь трекера с игрой. Значение
// показателя не смотрим никогда: важно, что человек честно отметил.
function знаетУтро(){
  const д = (typeof DATA !== "undefined" && DATA.today) || {};
  return д.sleep != null || д.mood != null || д.energy != null ||
         д.pulse != null || д.weight != null || д.steps != null || д.dist != null;
}

function autoPack(){
  const земля = PET.walkAim ?? PET.walkLand ?? 0;
  const тип = (PET.nextPlan && PET.nextPlan.route) || "тихая";
  const итог = autoShelf(земля, тип, expSeedFor(земля, тип), знаетУтро());
  PET.den = итог.полка;
  savePet();
  renderShelf();
  if(typeof renderFinds === "function") renderFinds();
  toast(итог.сообщение);
}

// ── Разрешение экспедиции ─────────────────────────────────────────────
// Считается один раз, из seed и снимка полки. Всё, что произошло в пути,
// выводится, а не бросается кубик заново при каждом открытии: перезагрузил
// приложение — те же встречи, тот же исход, та же добыча.
//
// Запас — это не здоровье. Рысь не ранена, не болеет и не умирает.
// Кончился запас — она разворачивается и приходит домой раньше.
function resolveExpedition(эксп){
  const сборка = shelfStats(эксп.gear || []);
  const s = {...сборка.s};
  const черта = эксп.trait;
  let запас = эксп.запас ?? 2;
  // Легендарное правило болота: дальний след начинается с тремя запасами.
  if(сборка.правило && сборка.правило.t === LEGEND_RULE[3] && эксп.route === "дальний") запас = 3;

  const шаги = [];
  const правило = сборка.правило ? сборка.правило.t : null;
  let спокойствиеЦело = (черта === "спокойствие");
  let смелостьЦела = (черта === "смелость");
  let универсал = (правило === LEGEND_RULE[8]);
  // Река: первая нехватка ловкости не тратит запас.
  let рекаЦела = (правило === LEGEND_RULE[1]);
  const сработали = [];

  // Обычный цикл, а не forEach: из forEach нельзя выйти, и запас уходил
  // в минус — рысь «продолжала» путь, которого уже не было.
  const узлы = эксп.nodes || [];
  for(let k = 0; k < узлы.length; k++){
    const у = узлы[k];
    const n = NODE_BY_ID[у.id];
    if(!n) continue;
    let нужно = у.нужно;
    let помощь = null;

    // Черта смелости снимает единицу с первой опасной встречи.
    if(смелостьЦела && n.s === "смелость"){ нужно--; смелостьЦела = false;
      помощь = {черта:"смелость", t:"смелая — первая опасность легче"}; }

    let закрыто = s[n.s] >= нужно;

    // Какая именно вещь сработала: первая на полке, дающая нужное.
    if(закрыто){
      // Срабатывает та вещь, что ещё не работала в этом пути: иначе
      // на всех трёх встречах подряд светится один и тот же камень,
      // и полка выглядит так, будто нужна была одна вещь из шести.
      const подходят = (эксп.gear || []).filter(i => {
        const p = gearProfile(i);
        return p && p.stat === n.s;
      });
      const вещь = подходят.find(i => !сработали.includes(i)) ?? подходят[0];
      if(вещь != null){ помощь = {вещь, t:FINDS[вещь] ? FINDS[вещь].n : ""}; сработали.push(вещь); }
    }

    // Не закрыто — пробуем правило «универсал», потом черту спокойствия,
    // и только потом тратим запас.
    let итог;
    if(закрыто){
      итог = "чисто";
    } else if(универсал){
      универсал = false; итог = "чисто";
      помощь = {правило:true, t:сборка.правило.t};
    } else if(рекаЦела && n.s === "ловкость"){
      рекаЦела = false; итог = "обошла";
      помощь = {правило:true, t:"Первая нехватка ловкости не стоила запаса"};
    } else if(спокойствиеЦело){
      спокойствиеЦело = false; итог = "обошла";
      помощь = {черта:"спокойствие", t:"спокойная — обошла, не потратив сил"};
    } else {
      запас--; итог = "обошла";
    }
    шаги.push({id:у.id, скрыт:у.скрыт, нужно:у.нужно, было:s[n.s], итог, помощь});
    // Запас кончился — дальше она не пошла. Оставшиеся узлы просто
    // не случились, и в разборе их нет.
    if(запас <= 0) break;
  }

  // Исход: чистый путь, обход или отступление.
  const обошла = шаги.filter(ш => ш.итог === "обошла").length;
  const дошла = запас > 0;
  const исход = !дошла ? "отступление" : (обошла ? "обход" : "чисто");

  return {шаги, запас, исход, сработали:[...new Set(сработали)],
    // Старая просека: после чистого пути можно выбрать один из двух.
    выбор: (исход === "чисто" && правило === LEGEND_RULE[2]),
    // Первый снег: встреча, из-за которой отступила, запоминается навсегда.
    запомнить: (исход === "отступление" && правило === LEGEND_RULE[7])};
}

// ── Что она принесла ──────────────────────────────────────────────────
// Не каждая прогулка приносит предмет, но каждая экспедиция меняет
// следующее решение. После отступления обязательно остаётся знание.
function expeditionResult(эксп, разбор){
  const земля = эксп.land ?? 0;
  const итог = {знание:null, находка:null, мастерство:разбор.сработали};
  // Отступление и обход всегда оставляют знание земли: где именно не хватило.
  const провал = разбор.шаги.find(ш => ш.итог === "обошла");
  if(провал){
    итог.знание = {земля, узел:провал.id,
      t:`Теперь известно: ${(NODE_BY_ID[провал.id]||{}).t || ""} — ${
        STATS[(NODE_BY_ID[провал.id]||{}).s].n.toLowerCase()} нужно ${провал.нужно}`};
  }
  if(разбор.исход === "отступление"){
    // Первый снег: та встреча, на которой она повернула, запоминается
    // навсегда — в следующий раз её требование будет известно заранее.
    if(разбор.запомнить){
      const последний = разбор.шаги[разбор.шаги.length - 1];
      if(последний) итог.знание = {земля, узел:последний.id,
        t:`Первый снег держит след: ${(NODE_BY_ID[последний.id]||{}).t} теперь известна навсегда.`};
    }
    // Предмета может не быть, но знание остаётся всегда.
    if(!итог.знание) итог.знание = {земля, узел:null, t:"Дорога до конца пока не пройдена."};
    // Нежность: даже после отступления она что-нибудь расскажет.
    if(эксп.trait === "нежность") итог.история = true;
    return итог;
  }
  // Дошла — есть добыча. Что именно, решает уже существующий walkLoot:
  // мы не заводим второй источник находок.
  итог.находка = true;
  return итог;
}

// ── Знание земли ──────────────────────────────────────────────────────
// Три ступени: знакомая, изученная, глубокая тропа. Без процентов —
// конкретными словами, что уже известно и чего не хватает.
function landKnow(земля){
  const k = landRecord(земля);
  return {чисто:k.clears, узлы:k.known, следы:k.clues};
}
function landStage(земля){
  const з = landKnow(земля);
  if(з.следы >= 3) return {n:3, t:"глубокая тропа"};
  if(з.узлы.length >= 2) return {n:2, t:"изученная"};
  if(з.чисто >= 1 || з.узлы.length) return {n:1, t:"знакомая"};
  return {n:0, t:"незнакомая"};
}
function landWords(земля){
  const з = landKnow(земля), ст = landStage(земля);
  if(!ст.n) return "Здесь она ещё не была.";
  const известно = з.узлы.length
    ? `Известно встреч: ${з.узлы.length}.` : "Встречи пока не изучены.";
  const до = 3 - з.следы;
  return `${ст.t[0].toUpperCase()+ст.t.slice(1)}. ${известно}` +
    (ст.n < 3 ? ` До глубокой тропы ${до} ${plural(до,"след","следа","следов")}.` : "");
}
// Запись земли могла приехать из облака неполной или остаться от прошлых
// версий: без этой защиты закрытие экспедиции падало на `known.includes`,
// и человек не получал результат целиком.
function landRecord(земля){
  const k = (PET.landKnowledge || {})[земля] || {};
  return {clears:k.clears || 0, clues:k.clues || 0,
          known:Array.isArray(k.known) ? k.known : []};
}
function rememberLand(земля, знание){
  PET.landKnowledge = {...(PET.landKnowledge || {})};
  const k = landRecord(земля);
  if(знание && знание.узел && !k.known.includes(знание.узел)) k.known = [...k.known, знание.узел];
  PET.landKnowledge[земля] = k;
}
function rememberClear(земля){
  PET.landKnowledge = {...(PET.landKnowledge || {})};
  const k = landRecord(земля);
  k.clears = k.clears + 1;
  if(k.clears % 2 === 0) k.clues = Math.min(3, (k.clues || 0) + 1);
  PET.landKnowledge[земля] = k;
}
// Мастерство: сработала вещь — след использования. Три раза, и она
// становится проверенной. Купить нельзя, потерять нельзя.
function rememberMastery(вещи){
  if(!вещи || !вещи.length) return;
  PET.itemMastery = {...(PET.itemMastery || {})};
  вещи.forEach(i => { PET.itemMastery[i] = (PET.itemMastery[i] || 0) + 1; });
}

// ── Начало экспедиции ─────────────────────────────────────────────────
// Вызывается из startWalk. Фиксирует снимок полки и seed: перестановка
// вещей во время прогулки уже начатый путь не меняет.
function startExpedition(земля, тип){
  // Seed тот же, что показывал экран подготовки. Сначала я подмешал сюда
  // Date.now(), и человек собирал полку под один маршрут, а рысь уходила
  // по другому: экран честно писал «закрыто 3 из 3», а в пути не хватало
  // ловкости. Подготовка обязана обещать ровно то, что будет.
  const seed = expSeedFor(земля, тип);
  const маршрут = buildRoute(земля, тип, seed, знаетУтро());
  // Любопытная видит один скрытый узел заранее. Легендарная из ближнего
  // леса — то же самое, но в любой земле.
  const черта = activeTrait();
  const сборка = shelfStats(PET.den || []);
  const правило = сборка.правило ? сборка.правило.t : null;
  const открыть = (черта === "любопытство") || (правило === LEGEND_RULE[0]);
  if(открыть) маршрут.узлы.forEach(у => { у.скрыт = false; });

  // Ночной лес: скрытая ночная встреча считается раскрытой.
  if(правило === LEGEND_RULE[5])
    маршрут.узлы.forEach(у => { if(у.id === "тьма") у.скрыт = false; });

  // Каменистая гряда: один известный узел дальнего следа можно заменить.
  // Меняем самый тяжёлый на такой же по смыслу, но полегче.
  if(правило === LEGEND_RULE[4] && тип === "дальний"){
    let тяж = -1, макс = 0;
    маршрут.узлы.forEach((у, k) => { if(!у.скрыт && у.нужно > макс){ макс = у.нужно; тяж = k; } });
    if(тяж >= 0) маршрут.узлы[тяж].нужно = 1;
  }

  // Поле на рассвете: один этап пути завершается раньше — в дальнем следе
  // на один узел меньше.
  if(правило === LEGEND_RULE[6] && маршрут.узлы.length > 2) маршрут.узлы.pop();

  PET.expedition = {
    id: Date.now(), seed, route: тип, land: земля,
    gear: [...(PET.den || [])],
    trait: черта,
    nodes: маршрут.узлы,
    запас: маршрут.запас,
    result: null, seen: 0
  };
  savePet();
  return PET.expedition;
}

// Путь из трёх узлов вместо таймера: пройдено, сейчас, впереди.
function walkPath(){
  const э = PET.expedition;
  if(!э || !э.nodes || !э.nodes.length) return "";
  const этап = (typeof walkStage === "function") ? walkStage() : 0;
  const всего = э.nodes.length;
  const сейчас = Math.min(всего - 1, Math.round(этап / 2 * (всего - 1)));
  return э.nodes.map((у, k) => {
    const n = NODE_BY_ID[у.id];
    const имя = у.скрыт ? "?" : (n ? n.t : "");
    if(k < сейчас) return `<span style="opacity:.45">${имя}</span>`;
    if(k === сейчас) return `<b>${имя}</b>`;
    return `<span style="opacity:.65">${имя}</span>`;
  }).join(`<span style="opacity:.3"> → </span>`);
}

// ── Вечерний разбор ───────────────────────────────────────────────────
// Один узел на нажатие. Видно, что произошло, какая вещь сработала
// и чего не хватило. Есть «показать сразу» для повторных экспедиций.
function expeditionStep(){
  const э = PET.expedition;
  if(!э) return null;
  if(!э.result) э.result = resolveExpedition(э);
  const шаги = э.result.шаги;
  const k = э.seen || 0;
  if(k >= шаги.length) return {конец:true, исход:э.result.исход, запас:э.result.запас};
  const ш = шаги[k];
  const n = NODE_BY_ID[ш.id] || {};
  return {
    конец:false, номер:k + 1, всего:шаги.length,
    t:n.t, д:n.д, итог:ш.итог,
    помощь:ш.помощь,
    нехватка: ш.итог === "обошла" && !ш.помощь
      ? `${STATS[n.s].n} ${ш.было} из ${ш.нужно}. Пришлось обходить.` : null
  };
}
function expeditionNext(){
  const э = PET.expedition;
  if(!э) return;
  э.seen = (э.seen || 0) + 1;
  savePet();
}
function expeditionSkip(){
  const э = PET.expedition;
  if(!э) return;
  if(!э.result) э.result = resolveExpedition(э);
  э.seen = э.result.шаги.length;
  savePet();
}

// Закрыть экспедицию: записать знание, мастерство, знание земли.
// Ничего не отнимаем: предметы, камни, земли и статистика на месте.
function closeExpedition(){
  const э = PET.expedition;
  if(!э) return null;
  if(!э.result) э.result = resolveExpedition(э);
  const итог = expeditionResult(э, э.result);
  rememberMastery(э.result.сработали);
  rememberExpedition(э, э.result);      // отсюда добыча узнает, как прошёл путь
  if(итог.знание) rememberLand(э.land, итог.знание);
  if(э.result.исход === "чисто") rememberClear(э.land);
  PET.expedition = null;
  savePet();
  return {итог, разбор:э.result};
}

// ── Сравнение новой вещи с полкой ─────────────────────────────────────
// Карточка обязана ответить: что делает, где полезна, что изменится,
// если поставить сейчас.
function compareToShelf(i, земля){
  const p = gearProfile(i);
  if(!p) return null;
  const полка = (PET.den || []).slice();
  const было = shelfStats(полка).s[p.stat];
  // Кого менять: первую вещь, чья характеристика не про эту землю
  // и которая слабее новой.
  let кого = null;
  полка.forEach(j => {
    if(кого != null) return;
    const q = gearProfile(j);
    if(!q) return;
    if(q.stat !== p.stat && q.земля !== земля) кого = j;
  });
  if(кого == null && полка.length >= 6) кого = полка[полка.length - 1];
  const после = было + p.сила;
  return {
    stat:p.stat, было, после, кого,
    t:`${STATS[p.stat].n} станет ${было} → ${после}.` +
      (кого != null && FINDS[кого] ? ` Можно поставить вместо: ${FINDS[кого].n}.` : "")
  };
}
function swapIntoShelf(новая, старая){
  PET.den = (PET.den || []).filter(x => x !== старая);
  if(!PET.den.includes(новая)) PET.den = [...PET.den, новая].slice(0, 6);
  savePet();
  if(typeof renderShelf === "function") renderShelf();
}

// ── Экран вечернего разбора ───────────────────────────────────────────
// Полноэкранный снимок земли, один узел на нажатие, две строки текста.
