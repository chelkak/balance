// вещи, поставленные раньше, просто становятся активными.
function shelfStats(полка){
  // Пока находок нет вообще, у рыси есть свои силы: по единице на всё.
  // Первая тихая тропа обязана пройтись и познакомить с системой —
  // иначе человек в первый день видит отступление и не понимает, за что.
  const новичок = !((PET && PET.finds) || []).length;
  const s = новичок ? {чутьё:1, ловкость:1, смелость:1}
                    : {чутьё:0, ловкость:0, смелость:0};
  const эффекты = [];
  let правило = null;
  (полка || []).forEach(i => {
    const p = gearProfile(i);
    if(!p) return;
    s[p.stat] += p.сила;
    // Проверенная вещь даёт дополнительную единицу: три срабатывания —
    // и предмет становится своим. Купить или потерять это нельзя.
    if(masteryOf(i) >= 3) s[p.stat] += 1;
    if(p.эффект) эффекты.push({i, t:p.эффект});
    // Одновременно активна только одна легендарная сила — первая на полке.
    if(p.правило && !правило) правило = {i, t:p.правило};
  });
  return {s, эффекты, правило};
}

const masteryOf = i => ((typeof PET !== "undefined" && PET.itemMastery) || {})[i] || 0;

// ── Маршрут ───────────────────────────────────────────────────────────
// Состав встреч выводится из seed и земли: у реки чаще вода, в ночном
// лесу чаще темнота. Полностью случайного набора нет — иначе сборка
// под землю не имела бы смысла.
function buildRoute(земля, тип, seed, знаетУтро){
  const пр = ROUTES[тип] || ROUTES.тихая;
  const спец = LAND_SPEC[земля] || LAND_SPEC[0];
  const свои = NODES.filter(n => n.s === спец.s);
  const чужие = NODES.filter(n => n.s !== спец.s);
  const узлы = [];
  const взятые = new Set();
  for(let k = 0; k < пр.узлов; k++){
    const r = expRand(seed, k + 1);
    // Две трети встреч — по теме земли, треть — любые: путь не должен
    // быть однообразным, но и не должен требовать всего сразу.
    const пул0 = (r < 0.66) ? свои : чужие;
    // Одна и та же встреча дважды за путь читается как ошибка, поэтому
    // уже взятые исключаем; кончились — берём из общего набора.
    let пул = пул0.filter(x => !взятые.has(x.id));
    if(!пул.length) пул = NODES.filter(x => !взятые.has(x.id));
    if(!пул.length) пул = пул0;
    const n = пул[Math.floor(expRand(seed, k + 50) * пул.length)];
    взятые.add(n.id);
    узлы.push({
      id: n.id,
      нужно: 1 + (expRand(seed, k + 100) < 0.35 ? 1 : 0),   // 1 или 2
      скрыт: false
    });
  }
  // Скрытый узел — последний. Утренняя запись показателей раскрывает его:
  // это единственная связь трекера с игрой, и она работает от факта
  // записи, а не от значения.
  if(пр.скрытых && узлы.length){
    узлы[узлы.length - 1].скрыт = !знаетУтро;
  }
  return {тип, узлы, запас: пр.запас};
}

// Сколько узлов маршрута закрывает текущая полка.
function routeCover(маршрут, сборка, черта){
  const s = {...сборка.s};
  let закрыто = 0, всего = 0;
  (маршрут.узлы || []).forEach((у, k) => {
    if(у.скрыт) return;                     // неизвестное не считаем
    всего++;
    const n = NODE_BY_ID[у.id];
    if(!n) return;
    let нужно = у.нужно;
    // Черта характера снимает единицу с первой встречи своего рода.
    if(черта === "смелость" && n.s === "смелость" && закрыто === 0) нужно--;
    if(s[n.s] >= нужно) закрыто++;
  });
  return {закрыто, всего};
}

// ── Авто-сборка ───────────────────────────────────────────────────────
// «Собрать лучшее» для человека, который не хочет разбираться. Берёт
// только найденные вещи, максимум шесть, и честно говорит, если улучшить
// нечем.
function autoShelf(земля, тип, seed, знаетУтро){
  const мои = ((typeof PET !== "undefined" && PET.finds) || []).filter(i => gearProfile(i));
  if(!мои.length) return {полка:[], сообщение:"Находок пока нет — пойдёт налегке."};
  const маршрут = buildRoute(земля, тип, seed, знаетУтро);
  // Сколько какой характеристики просит маршрут.
  const нужно = {чутьё:0, ловкость:0, смелость:0};
  (маршрут.узлы || []).forEach(у => {
    if(у.скрыт) return;
    const n = NODE_BY_ID[у.id];
    if(n) нужно[n.s] = Math.max(нужно[n.s], у.нужно);
  });
  // Жадно: сначала то, чего не хватает больше всего.
  const полка = [];
  const есть = {чутьё:0, ловкость:0, смелость:0};
  const остались = мои.slice();
  let легендарная = false;
  while(полка.length < 6 && остались.length){
    let лучший = -1, лучшийБалл = -Infinity;
    остались.forEach((i, k) => {
      const p = gearProfile(i);
      if(p.правило && легендарная) return;         // вторую легендарную не берём
      const дефицит = Math.max(0, нужно[p.stat] - есть[p.stat]);
      let балл = дефицит * 10 + (p.эффект ? 3 : 0) + (p.правило ? 4 : 0) + p.r;
      if(своя(p, земля)) балл += 2;
      if(балл > лучшийБалл){ лучшийБалл = балл; лучший = k; }
    });
    if(лучший < 0) break;
    const i = остались.splice(лучший, 1)[0];
    const p = gearProfile(i);
    полка.push(i);
    есть[p.stat] += p.сила + (masteryOf(i) >= 3 ? 1 : 0);
    if(p.правило) легендарная = true;
  }
  const после = routeCover(маршрут, shelfStats(полка), activeTrait());
  return {полка, маршрут,
    сообщение: после.всего
      ? `Закрыто ${после.закрыто} из ${после.всего} известных встреч.`
      : "Все встречи этого пути пока неизвестны."};
}
// Вещь из той же земли, куда идём, чуть полезнее: её эффект про это место.
function своя(p, земля){ return p.земля === земля; }

// ── Характер ──────────────────────────────────────────────────────────
// Доминирующая черта даёт одно заметное последствие. При равенстве
// активна та, что проявлена позже.
function activeTrait(){
  const т = (typeof PET !== "undefined" && PET.traits) || {};
  const когда = (typeof PET !== "undefined" && PET.traitAt) || {};
  let лучшая = null, макс = 0, позже = 0;
  Object.entries(т).forEach(([k, v]) => {
    if(v > макс || (v === макс && (когда[k] || 0) > позже)){
      макс = v; лучшая = k; позже = когда[k] || 0;
    }
  });
  return макс > 0 ? лучшая : null;
}
