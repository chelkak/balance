  if(!window.__flashed){
    window.__flashed=true;
    const tk=todayKey();
    let вчера=null;
    for(let i=DAYS.length-1;i>=0;i--){
      if(keyOf(DAYS[i].date)!==tk){вчера=DAYS[i].touched||[];break;}
    }
    (вчера||[]).forEach(code=>{
      document.querySelectorAll(`#totem .bp[data-code="${code}"]`).forEach(el=>el.classList.add("flash"));
    });
  }
