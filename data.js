function walkStage(){
  if(!isWalking()) return 0;
  const всего=walkBackTime()-PET.walkStart;
  if(всего<=0) return 2;
  const доля=(Date.now()-PET.walkStart)/всего;
  return доля<0.45?0:доля<0.8?1:2;
}

