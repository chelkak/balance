// ── Рысь держит день ──────────────────────────────────────────────────
// Раньше кадр взрослой рыси выбирался одним выражением по режиму:
// красный — свернулась, жёлтый — любопытная, иначе довольная. Режим
// считается по настроению за три дня, поэтому состояние менялось редко
// и без видимой причины: человек внёс цифры, а на экране ничего.
//
// Теперь состояние выбирается по сегодняшнему дню и держится до следующего
// его этапа. У каждого изменения есть причина, и её можно назвать словами —
// это важнее самого кадра: «она такая, потому что ты спал пять часов».
//
// Кадры только существующие. «Грустная» и «сердитая» лежат в pet/ и
// намеренно не подключены: зверь не осуждает за плохой день.
//
// Порядок проверок — от самого весомого к обычному.
function petState(){
  const ночь=timeKey()==="night";
  const серый=isGrey(todayKey());
  const д=DATA.today||{};
  const m=mode();

  // Ночь сильнее всего: спящий кадр вместо тёмного прямоугольника поверх
  // бодрой рыси. Это про время суток, а не про то, каким был день.
  if(ночь) return {k:"10-sleepy",w:"ночь, она спит"};

  // Серый день ничего не оценивает — человек сам сказал, что он выпал.
  if(серый) return {k:"10-neutral",w:"сегодня не в счёт, она просто рядом"};

  // Красный режим: честный отдых, никаких продуктивных намёков.
  if(m==="red") return {k:"10-rest",w:"тяжёлые дни, она никуда не зовёт"};

  // Дальше — по сегодняшним показателям, но только если они внесены.
  // Ничего не внесено — обычный кадр, а не выдуманное состояние.
  const сон=д.sleep, эн=д.energy, наст=д.mood;
  const мало=v=>v!=null&&v<=4;

  if(мало(эн)||мало(наст)) return {k:"10-rest",w:"ты отметил, что сегодня тяжело"};
  if(сон!=null&&сон<6)     return {k:"10-neutral",w:`спал ${(+сон).toFixed(1)} ч — она рядом, но тихо`};
  if(эн!=null&&эн>=8)      return {k:"10-curious",w:"энергии много, ей интересно"};
  if(наст!=null&&наст>=8)  return {k:"10-happy",w:"хороший день, и это видно"};

  // Вчерашний день, если сегодня ещё ничего не вносили: состояние
  // не берётся из ниоткуда, у него всегда есть причина.
  const вчера=DAYS.filter(d=>!d.grey).slice(-1)[0];
  if(сон==null&&эн==null&&наст==null&&вчера){
    if(вчера.energy!=null&&вчера.energy<=4) return {k:"10-neutral",w:"вчера было тяжело, она не торопит"};
    if(вчера.sleep!=null&&вчера.sleep>=7.5) return {k:"10-curious",w:"ты выспался — она уже на ногах"};
  }
  return {k:"10-happy",w:"обычный день"};
}


