// ── Рысь держит день ──────────────────────────────────────────────────
// Раньше кадр взрослой рыси выбирался одним выражением по режиму:
// красный — свернулась, жёлтый — любопытная, иначе довольная. Режим
// считается по настроению за три дня, поэтому состояние менялось редко
// и без видимой причины: человек внёс цифры, а на экране ничего.
//
// Теперь состояние выбирается по сегодняшнему дню и держится до следующего
// его этапа. У каждого изменения есть причина, и её можно назвать словами —
// это важнее самого кадра: «она такая, потому что ты спал пять часов».
//
// Кадры только существующие. «Грустная» и «сердитая» лежат в pet/ и
// намеренно не подключены: зверь не осуждает за плохой день.
//
// Порядок проверок — от самого весомого к обычному.
// Кадр состояния для текущей стадии: у взрослой они есть всегда, у младших
// появляются по мере того, как художник их присылает. Нет кадра — остаётся
// обычный дневной, и это не поломка.
function состояниеКадр(вид, слова){
  const к = (typeof moodFrame === "function") ? moodFrame(вид) : `10-${вид}`;
  return к ? {k:к, w:слова} : null;
}
function petState(){
  const ночь=timeKey()==="night";
  const серый=isGrey(todayKey());
  const д=DATA.today||{};
  const m=mode();

  // Ночь сильнее всего: спящий кадр вместо тёмного прямоугольника поверх
  // бодрой рыси. Это про время суток, а не про то, каким был день.
  // Ночной кадр стадии подставляет currentPhotoKey ещё до этой функции.
  // Сюда доходит только случай, когда ночного кадра для стадии нет —
  // тогда берём спящий взрослый лишь для взрослой, малышу его нельзя.
  if(ночь) return состояниеКадр("sleepy","ночь, она спит")
                || {k:String(stageNow()), w:"ночь, она спит"};

  // Серый день ничего не оценивает — человек сам сказал, что он выпал.
  if(серый) return состояниеКадр("neutral","сегодня не в счёт, она просто рядом")
                 || состояниеКадр("rest","сегодня не в счёт, она просто рядом")
                 || {k:String(stageNow()), w:"сегодня не в счёт, она просто рядом"};

  // Красный режим: честный отдых, никаких продуктивных намёков.
  if(m==="red") return состояниеКадр("rest","тяжёлые дни, она никуда не зовёт")
                      || {k:String(stageNow()), w:"тяжёлые дни, она никуда не зовёт"};

  // Дальше — по сегодняшним показателям, но только если они внесены.
  // Ничего не внесено — обычный кадр, а не выдуманное состояние.
  const сон=д.sleep, эн=д.energy, наст=д.mood;
  const мало=v=>v!=null&&v<=4;

  if(мало(эн)||мало(наст)) return состояниеКадр("rest","ты отметил, что сегодня тяжело")
                                 || {k:String(stageNow()), w:"ты отметил, что сегодня тяжело"};
  if(сон!=null&&сон<6)     return состояниеКадр("neutral",`спал ${(+сон).toFixed(1)} ч — она рядом, но тихо`)
                                 || состояниеКадр("rest",`спал ${(+сон).toFixed(1)} ч — она рядом, но тихо`)
                                 || {k:String(stageNow()), w:`спал ${(+сон).toFixed(1)} ч — она рядом, но тихо`};
  if(эн!=null&&эн>=8)      return состояниеКадр("curious","энергии много, ей интересно")
                                 || состояниеКадр("happy","энергии много, ей интересно")
                                 || {k:String(stageNow()), w:"энергии много, ей интересно"};
  if(наст!=null&&наст>=8)  return состояниеКадр("happy","хороший день, и это видно")
                                 || {k:String(stageNow()), w:"хороший день, и это видно"};

  // Вчерашний день, если сегодня ещё ничего не вносили: состояние
  // не берётся из ниоткуда, у него всегда есть причина.
  const вчера=DAYS.filter(d=>!d.grey).slice(-1)[0];
  if(сон==null&&эн==null&&наст==null&&вчера){
    if(вчера.energy!=null&&вчера.energy<=4)
      return состояниеКадр("neutral","вчера было тяжело, она не торопит")
          || состояниеКадр("rest","вчера было тяжело, она не торопит")
          || {k:String(stageNow()), w:"вчера было тяжело, она не торопит"};
    if(вчера.sleep!=null&&вчера.sleep>=7.5)
      return состояниеКадр("curious","ты выспался — она уже на ногах")
          || состояниеКадр("happy","ты выспался — она уже на ногах")
          || {k:String(stageNow()), w:"ты выспался — она уже на ногах"};
  }
  return состояниеКадр("neutral","обычный день")
      || состояниеКадр("happy","обычный день")
      || {k:String(stageNow()), w:"обычный день"};
}


