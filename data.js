const KINDS=["ряд","удвоение","фибоначчи","лишнее","сумма","зеркало",
             "умножение","двойное","доли","разность","процент"];
let ПОСЛЕДНИЙ_ВИД=null;
function makePuzzle(избегать){
  const R=n=>Math.floor(Math.random()*n);
  const ур=stageNow();                       // 1..10 — растёт вместе с рысью
  const К=1+Math.floor(ур/3);                // множитель сложности: 1..4
  const mix=a=>{a=[...a];for(let i=a.length-1;i>0;i--){const j=R(i+1);[a[i],a[j]]=[a[j],a[i]];}return a;};
  const uniq=(ans,alt)=>{const s=new Set([ans]);alt.forEach(v=>{if(v!==ans&&v>0)s.add(v);});
    const out=[...s].slice(0,4);
    while(out.length<4){const v=ans+1+R(9);if(!out.includes(v))out.push(v);}
    return mix(out);};
  // Виды все и сразу: сложность растёт числами, а не запретами. Раньше
  // новичку доставались шесть простейших, из которых три выглядели одинаково.
  // Внутри одного дня вид не повторяется — три задачки, три разных.
  const свободные=KINDS.filter(k=>!(избегать||[]).includes(k));
  const вид=(свободные.length?свободные:KINDS)[R(свободные.length||KINDS.length)];
  ПОСЛЕДНИЙ_ВИД=вид;
  switch(вид){
    case "ряд":{const a=2+R(9*К),d=2+R(8*К),ans=a+4*d;
      return {q:`Продолжи ряд: ${a}, ${a+d}, ${a+2*d}, ${a+3*d}, ?`,ans,opts:uniq(ans,[ans+d,ans-d,ans+1])};}
    case "удвоение":{const b=2+R(5*К),ans=b*16;
      return {q:`Какое число следующее: ${b}, ${b*2}, ${b*4}, ${b*8}, ?`,ans,opts:uniq(ans,[ans+b,ans-b,ans*2])};}
    case "фибоначчи":{const a=1+R(5),b=a+1+R(4*К),s=[a,b,a+b,a+2*b,2*a+3*b],ans=3*a+5*b;
      return {q:`Угадай правило и продолжи: ${s.join(", ")}, ?`,ans,opts:uniq(ans,[ans+1,ans-2,ans+b])};}
    case "лишнее":{const base=2+R(6*К),arr=[base*2,base*4,base*6,base*8],odd=base*5+1;
      arr[R(4)]=odd;
      return {q:`Что здесь лишнее: ${arr.join(", ")}?`,ans:odd,opts:mix(arr)};}
    case "сумма":{const a=11+R(60*К),b=11+R(60*К),ans=a+b;
      return {q:`Сколько будет ${a} + ${b}?`,ans,opts:uniq(ans,[ans+9,ans-10,ans+1])};}
    case "умножение":{const a=3+R(9+3*К),b=3+R(9+2*К),ans=a*b;
      return {q:`Сколько будет ${a} × ${b}?`,ans,opts:uniq(ans,[ans+a,ans-b,ans+10])};}
    case "двойное":{const a=1+R(6),d=2+R(5),m=2,s=[a,a*m+d,(a*m+d)*m+d,((a*m+d)*m+d)*m+d];
      const ans=s[3]*m+d;
      return {q:`Ряд по правилу «умножь на ${m}, прибавь ${d}»: ${s.join(", ")}, ?`,ans,
              opts:uniq(ans,[ans+d,ans-m,ans+m*d])};}
    case "доли":{const ч=2+R(3),всего=ч*(4+R(8*К)),ans=всего/ч;
      return {q:`${всего} разделить на ${ч} — сколько?`,ans,opts:uniq(ans,[ans+ч,ans-1,ans*2])};}
    case "разность":{const a=40+R(90*К),b=11+R(38),ans=a-b;
      return {q:`Сколько будет ${a} − ${b}?`,ans,opts:uniq(ans,[ans+9,ans-11,ans+1])};}
    case "процент":{const б=[10,20,25,50][R(4)],ц=б*(2+R(9*К)),ans=Math.round(ц*б/100);
      return {q:`Сколько будет ${б}% от ${ц}?`,ans,opts:uniq(ans,[ans+б,Math.round(ans/2),ans+1])};}
    default:{const n=100+R(800),ans=+String(n).split("").reverse().join("");
      return {q:`Прочитай число задом наперёд: ${n}`,ans,opts:uniq(ans,[ans+11,ans-9,n])};}
  }
}
